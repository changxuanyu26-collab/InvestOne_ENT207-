#!/usr/bin/env python3
"""Account persistence and temporary guest acceptance; no AI calls."""
import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

BASE = os.environ.get("INVESTONE_LIVE_URL", "http://localhost:18893").rstrip("/")
OUTPUT = Path(os.environ.get("INVESTONE_QA_OUTPUT", "/tmp/investone-name-qa"))
OUTPUT.mkdir(parents=True, exist_ok=True)
NAME = "张同学 Sam"

def access(page):
    page.goto(BASE + "/app/", wait_until="domcontentloaded")
    page.locator("#account-form").wait_for(timeout=30000)
    assert page.locator('input[type="password"]').count() == 1
    assert page.get_by_role("button", name="Create account", exact=True).count() == 1

def enter(page):
    page.locator('#visitor-form input[name="username"]').fill(NAME)
    page.get_by_role("button", name="Continue without an account", exact=True).click()
    page.locator("nav .nav-item").first.wait_for(timeout=30000)
    expect(page.locator(".userbox")).to_contain_text(NAME)

with sync_playwright() as pw:
    browser = pw.chromium.launch(headless=True, executable_path=os.environ.get("PLAYWRIGHT_EXECUTABLE_PATH") or None)
    headers = {"X-Forwarded-Proto": "http"} if BASE.startswith("http:") else {}
    ctx = browser.new_context(viewport={"width": 1365, "height": 950}, extra_http_headers=headers)
    page = ctx.new_page()
    errors = []
    page.on("pageerror", lambda e: errors.append(str(e)))
    access(page)
    page.screenshot(path=str(OUTPUT / "name-entry-desktop.png"), full_page=True)
    enter(page)
    page.get_by_role("link", name="Personalised Intelligence", exact=True).click()
    page.locator('#profile-form select[name="risk"]').select_option("High")
    page.locator('#profile-form button[type="submit"]').click()
    expect(page.locator("#toast")).to_contain_text("Settings saved")
    page.reload(wait_until="domcontentloaded")
    page.locator("nav .nav-item").first.wait_for(timeout=30000)
    expect(page.locator('#profile-form select[name="risk"]')).to_have_value("Moderate")
    page.locator('.account-entry[data-action="logout"]').click()
    page.locator("#account-form").wait_for()
    page.reload(wait_until="domcontentloaded")
    page.locator("#account-form").wait_for()
    enter(page)
    page.get_by_role("link", name="Personalised Intelligence", exact=True).click()
    expect(page.locator('#profile-form select[name="risk"]')).to_have_value("Moderate")
    print("PASS: browser visitor entry, refresh, sign-out and temporary browser data", flush=True)
    second = browser.new_context(viewport={"width": 1280, "height": 850}, extra_http_headers=headers)
    other = second.new_page()
    access(other)
    enter(other)
    other.get_by_role("link", name="Personalised Intelligence", exact=True).click()
    expect(other.locator('#profile-form select[name="risk"]')).to_have_value("Moderate")
    print("PASS: identical names in different browsers do not share data", flush=True)
    mobile = browser.new_context(viewport={"width": 390, "height": 844}, is_mobile=True, extra_http_headers=headers)
    small = mobile.new_page()
    access(small)
    assert small.evaluate("document.documentElement.scrollWidth <= innerWidth")
    small.screenshot(path=str(OUTPUT / "name-entry-mobile.png"), full_page=True)
    enter(small)
    expect(small.locator(".account-entry")).to_be_visible()
    assert not errors, "Browser runtime errors occurred"
    print("PASS: mobile name entry and visible sign-out; no browser errors", flush=True)
    account_ctx = browser.new_context(extra_http_headers=headers)
    account_page = account_ctx.new_page()
    access(account_page)
    import uuid
    username = "qa-" + uuid.uuid4().hex[:12]
    account_page.locator('#account-form input[name="username"]').fill(username)
    account_page.locator('#account-form input[name="password"]').fill("test-password-123")
    account_page.get_by_role("button", name="Create account", exact=True).click()
    account_page.locator("nav .nav-item").first.wait_for()
    account_page.goto(BASE + "/app/#quant")
    account_page.locator('#quant-form input[name="top_n"]').fill("2")
    account_page.get_by_role("button", name="Save selection settings", exact=True).click()
    expect(account_page.locator("#toast")).to_contain_text("Selection settings saved")
    account_page.reload()
    expect(account_page.locator('#quant-form input[name="top_n"]')).to_have_value("2")
    device = browser.new_context(extra_http_headers=headers)
    device_page = device.new_page()
    access(device_page)
    device_page.locator('#account-form input[name="username"]').fill(username)
    device_page.locator('#account-form input[name="password"]').fill("test-password-123")
    device_page.get_by_role("button", name="Sign in", exact=True).click()
    device_page.locator("nav .nav-item").first.wait_for()
    device_page.goto(BASE + "/app/#quant")
    expect(device_page.locator('#quant-form input[name="top_n"]')).to_have_value("2")
    device_page.locator('.account-entry[data-action="logout"]').click()
    device_page.reload()
    device_page.locator("#account-form").wait_for()
    print("PASS: registration, saved strategy, reload, cross-device login and logout", flush=True)
    # Pausing saving preserves the last saved account data across refreshes,
    # while current-page edits are discarded. Turning saving on saves edits.
    account_page.goto(BASE + "/app/#settings")
    account_page.locator('#record-saving-form input[name="save_records"]').uncheck()
    account_page.locator('#record-saving-form button').click()
    expect(account_page.locator("#toast")).to_contain_text("Record saving paused")
    account_page.locator('#profile-form select[name="risk"]').select_option("High")
    account_page.locator('#profile-form button[type="submit"]').click()
    expect(account_page.locator("#toast")).to_contain_text("Settings saved")
    expect(account_page.locator('#profile-form select[name="risk"]')).to_have_value("High")
    account_page.reload()
    expect(account_page.locator('#profile-form select[name="risk"]')).to_have_value("Moderate")
    expect(account_page.locator('#record-saving-form input[name="save_records"]')).not_to_be_checked()
    account_page.locator('#profile-form select[name="risk"]').select_option("High")
    account_page.locator('#profile-form button[type="submit"]').click()
    expect(account_page.locator("#toast")).to_contain_text("Settings saved")
    account_page.locator('#record-saving-form input[name="save_records"]').check()
    account_page.locator('#record-saving-form button').click()
    expect(account_page.locator("#toast")).to_contain_text("Record saving enabled")
    account_page.reload()
    expect(account_page.locator('#profile-form select[name="risk"]')).to_have_value("High")
    account_page.locator('.account-entry[data-action="logout"]').click()
    account_page.locator('#account-form').wait_for()
    account_page.locator('#account-form input[name="username"]').fill(username)
    account_page.locator('#account-form input[name="password"]').fill("test-password-123")
    account_page.locator('#account-form input[name="save_records"]').uncheck()
    account_page.get_by_role("button", name="Sign in", exact=True).click()
    account_page.locator("nav .nav-item").first.wait_for()
    account_page.goto(BASE + "/app/#settings")
    expect(account_page.locator('#record-saving-form input[name="save_records"]')).not_to_be_checked()
    expect(account_page.locator('#profile-form select[name="risk"]')).to_have_value("High")
    account_page.locator('#profile-form select[name="risk"]').select_option("Low")
    account_page.locator('#profile-form button[type="submit"]').click()
    expect(account_page.locator("#toast")).to_contain_text("Settings saved")
    account_page.reload()
    expect(account_page.locator('#profile-form select[name="risk"]')).to_have_value("High")
    print("PASS: per-sign-in saving choice; pause discards new edits on refresh; enabling saves current records", flush=True)
    browser.close()
